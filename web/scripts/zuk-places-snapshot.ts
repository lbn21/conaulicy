// npm run zuk:places [-- --teryt <dir>] [-- --check]: rewrites
// lib/zuk-places.generated.ts,
// our places (every locality and street of our gminy, each street with its
// TERYT CECHA and NAZWA_1) from the TERYT files archived in
// etl/sources.yaml: what the ZUK prompt and gate read (lib/zuk-cron.ts), in
// production and in CI, with no database or network. Reads the newest archived SIMC and ULIC files from
// .cache/sources/ (npm run sources:pull) and checks their SHA-256; --teryt
// reads another directory. Run it whenever the TERYT files in
// etl/sources.yaml change (a reviewed TERYT difference, docs/database.md).
// --check writes nothing and fails if the committed file differs: the
// import workflow runs it, as it alone can read the archive.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";
import {
  archiveKey,
  gminaTercs,
  loadConfig,
  ROOT,
} from "./import/core/config.ts";
import { sha256 } from "./import/core/hash.ts";
import { parseSimc, parseUlic, placeRows } from "./lib/teryt.ts";

const OUT = path.join(ROOT, "web/lib/zuk-places.generated.ts");
const { values: args } = parseArgs({
  options: { teryt: { type: "string" }, check: { type: "boolean" } },
});
const config = loadConfig();

const tercs = gminaTercs(config);

const teryt = config.archived.filter((a) => a.origin === "teryt");
const newest = teryt
  .map((a) => a.fetched)
  .sort()
  .at(-1);
const files = teryt
  .filter((a) => a.fetched === newest)
  .map((a) => {
    const file = args.teryt
      ? path.resolve(args.teryt, a.file)
      : path.join(ROOT, ".cache", archiveKey(a));
    const body = readFileSync(file);
    if (!args.teryt && sha256(body) !== a.sha256)
      throw new Error(`${file}: SHA-256 is not etl/sources.yaml's`);
    return { name: a.file, key: archiveKey(a), text: body.toString("utf8") };
  });
const of = (prefix: string) => files.filter((f) => f.name.startsWith(prefix));
const rows = placeRows(
  of("ULIC_").flatMap((f) => parseUlic(f.text)),
  of("SIMC_").flatMap((f) => parseSimc(f.text)),
  tercs,
);

const lines = (list: string[]) => list.map((l) => `${l}\n`).join("");
const kinds = rows.localities.map((l) => l.split(";")[2]);
const count = (kind: string) => kinds.filter((k) => k === kind).length;
const body = `// Generated by \`npm run zuk:places\` (scripts/zuk-places-snapshot.ts); do
// not edit. Every locality and street TERYT has for gminy ${tercs.join(", ")}:
// ${count("miasto")} town, ${count("wies")} villages, ${count("czesc_wsi")} village parts (with a parent; the town's
// parts among them) and ${rows.streets.length} streets, each with its CECHA and NAZWA_1. From
${files.map((f) => `// ${f.key}`).join("\n")}
// (etl/sources.yaml). What the ZUK prompt and gate read, in production and
// in the tests; code, not data (scripts/check-tracked-data.mjs).

import type { ZukPlaces } from "./zuk-resolve.ts";

// SIMC;name;kind;parent SIMC
const LOCALITIES = \`
${lines(rows.localities)}\`;

// SIMC-SYM_UL;SIMC;name;CECHA;NAZWA_1
const STREETS = \`
${lines(rows.streets)}\`;

const split = (text: string) =>
  text
    .trim()
    .split("\\n")
    .map((line) => line.split(";"));

export const ZUK_PLACES: ZukPlaces = {
  localities: split(LOCALITIES).map(([id, name, kind, parentId]) => ({
    id,
    name,
    kind: kind as ZukPlaces["localities"][number]["kind"],
    parentId: parentId || null,
  })),
  streets: split(STREETS).map(([id, localityId, name, cecha, name1]) => ({
    id,
    localityId,
    name,
    cecha,
    name1,
  })),
};
`;
if (args.check) {
  const committed = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (committed !== body) {
    console.error(
      `${path.relative(ROOT, OUT)} differs from the archived TERYT files: run npm run sources:pull && npm run zuk:places, and commit it.`,
    );
    process.exit(1);
  }
  console.log(`${path.relative(ROOT, OUT)}: matches the archived TERYT files.`);
  process.exit(0);
}
writeFileSync(OUT, body);
console.log(
  `${path.relative(ROOT, OUT)}: ${rows.localities.length} localities, ${rows.streets.length} streets.`,
);
